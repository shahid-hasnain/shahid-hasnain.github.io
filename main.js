/* ---------- home page: reveal on scroll and counting numbers ---------- */
(function(){
  const still=window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  const items=document.querySelectorAll('.reveal');
  const nums=document.querySelectorAll('[data-count]');
  function count(el){
    const end=+el.dataset.count, suf=el.dataset.suffix||'', t0=performance.now(), dur=1400;
    (function step(t){
      const k=Math.min(1,(t-t0)/dur), e=1-Math.pow(1-k,3);
      el.textContent=Math.round(end*e)+suf;
      if(k<1)requestAnimationFrame(step);
    })(t0);
  }
  if(still||!('IntersectionObserver' in window)){items.forEach(i=>i.classList.add('in'));return;}
  const io=new IntersectionObserver(es=>es.forEach(e=>{
    if(!e.isIntersecting)return;
    e.target.classList.add('in');
    e.target.querySelectorAll('[data-count]').forEach(count);
    io.unobserve(e.target);
  }),{threshold:.15});
  items.forEach(i=>io.observe(i));
  nums.forEach(n=>{if(!n.closest('.reveal'))count(n)});
})();


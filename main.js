(function(){
  const f=document.getElementById('enquiry'); if(!f)return;
  const status=f.querySelector('.form-status'), btn=f.querySelector('.send');
  const say=(t,c)=>{status.textContent=t;status.className='form-status'+(c?' '+c:'')};
  function check(){
    let ok=true;
    f.querySelectorAll('[required]').forEach(el=>{
      const bad=!el.value.trim()||(el.type==='email'&&!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(el.value));
      el.closest('.field').classList.toggle('bad',bad); if(bad)ok=false;
    });
    return ok;
  }
  f.addEventListener('input',e=>{const fl=e.target.closest('.field'); if(fl)fl.classList.remove('bad')});
  f.addEventListener('submit',async e=>{
    e.preventDefault();
    if(!check()){say('Please fill in the highlighted fields.','err');return;}
    const d=new FormData(f);
    if(f.action.includes('YOUR_FORM_ID')){
      /* form service not connected yet: open the visitor's email app instead */
      const body=`Name: ${d.get('name')}\nEmail: ${d.get('email')}\nEnquiry type: ${d.get('enquiry_type')}\nPreferred mode: ${d.get('mode')}\n\n${d.get('message')}`;
      location.href='mailto:shahid.hasnain@uoc.edu.pk?subject='+encodeURIComponent('Website enquiry: '+d.get('enquiry_type'))+'&body='+encodeURIComponent(body);
      say('Opening your email app…');return;
    }
    btn.disabled=true; say('Sending…');
    try{
      const r=await fetch(f.action,{method:'POST',body:d,headers:{Accept:'application/json'}});
      if(r.ok){f.reset(); say('Thank you, your message has been sent. I will reply soon.','ok');}
      else say('Sorry, something went wrong. Please email me directly.','err');
    }catch(err){say('Sorry, the message could not be sent. Please check your connection or email me directly.','err');}
    btn.disabled=false;
  });
})();
